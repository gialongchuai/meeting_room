-- Enable btree_gist extension for exclusion constraints
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- 1. Equipment table
CREATE TABLE equipment (
    equipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) UNIQUE NOT NULL,
    name_vi VARCHAR(100) NOT NULL,
    name_en VARCHAR(100) NOT NULL,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

-- 2. App User table
CREATE TABLE app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150) UNIQUE NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    department VARCHAR(100),
    role VARCHAR(15) NOT NULL,
    status VARCHAR(10) NOT NULL,
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_count INT NOT NULL DEFAULT 0,
    locked_until BIGINT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

-- 3. Room table
CREATE TABLE room (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) UNIQUE NOT NULL,
    name_vi VARCHAR(100) NOT NULL,
    name_en VARCHAR(100) NOT NULL,
    description_vi VARCHAR(500),
    description_en VARCHAR(500),
    capacity INT NOT NULL,
    floor VARCHAR(10),
    status VARCHAR(15) NOT NULL,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

-- 4. Room Equipment table (M:N)
CREATE TABLE room_equipment (
    room_id BIGINT NOT NULL REFERENCES room(room_id) ON DELETE CASCADE,
    equipment_id BIGINT NOT NULL REFERENCES equipment(equipment_id) ON DELETE CASCADE,
    PRIMARY KEY (room_id, equipment_id)
);

-- 5. Booking table
CREATE TABLE booking (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES room(room_id),
    booked_by BIGINT NOT NULL REFERENCES app_user(user_id),
    title VARCHAR(200) NOT NULL,
    description VARCHAR(1000),
    attendee_count INT NOT NULL,
    start_time BIGINT NOT NULL,
    end_time BIGINT NOT NULL,
    status VARCHAR(15) NOT NULL,
    cancelled_by BIGINT REFERENCES app_user(user_id),
    cancel_reason VARCHAR(255),
    cancelled_at BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

-- Exclusion constraints for zero double-booking tolerance
ALTER TABLE booking
    ADD CONSTRAINT ex_booking_no_overlap
    EXCLUDE USING gist (
        room_id WITH =,
        int8range(start_time, end_time, '[)') WITH &&
    ) WHERE (status = 'CONFIRMED');

ALTER TABLE booking
    ADD CONSTRAINT ex_booking_user_no_overlap
    EXCLUDE USING gist (
        booked_by WITH =,
        int8range(start_time, end_time, '[)') WITH &&
    ) WHERE (status = 'CONFIRMED');

-- 6. Booking History table (Audit log)
CREATE TABLE booking_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES booking(booking_id) ON DELETE CASCADE,
    action VARCHAR(20) NOT NULL,
    old_start_time BIGINT,
    old_end_time BIGINT,
    new_start_time BIGINT,
    new_end_time BIGINT,
    actor_id BIGINT NOT NULL REFERENCES app_user(user_id),
    note VARCHAR(255),
    created_at BIGINT NOT NULL
);

-- Indexes
CREATE INDEX idx_booking_room_time ON booking(room_id, start_time, end_time) WHERE status = 'CONFIRMED';
CREATE INDEX idx_booking_booked_by ON booking(booked_by, start_time DESC);
CREATE INDEX idx_room_status ON room(status);
CREATE INDEX idx_booking_history_booking_id ON booking_history(booking_id, created_at DESC);
